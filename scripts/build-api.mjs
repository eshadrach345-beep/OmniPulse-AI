// Bundles server/*.ts into api/index.js without esbuild (uses the TypeScript compiler only).
// Usage: node scripts/build-api.mjs   (needs `typescript` installed: npm i -D typescript)
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
let ts;
try { ts = require('typescript'); } catch { ts = require(path.join(process.env.TS_PATH || '/home/claude/.npm-global/lib/node_modules/typescript')); }

const order = ['lib/core.ts', 'lib/db.ts', 'lib/plans.ts', 'lib/services.ts', 'lib/prompts.ts', 'lib/merge.ts', 'lib/postpeer.ts', 'lib/social.ts', 'handler.ts'];
const externals = new Map(); // module -> Set of names
let body = '';
const seen = new Map();
for (const f of order) {
  const src = fs.readFileSync(path.join('server', f), 'utf8');
  let js = ts.transpileModule(src, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext, importsNotUsedAsValues: 0 } }).outputText;
  // pull out imports
  js = js.replace(/^import\s+([\s\S]*?)\s+from\s+['"]([^'"]+)['"];?\s*$/gm, (_, what, mod) => {
    if (mod.startsWith('.')) return '';
    const set = externals.get(mod) || new Set(); externals.set(mod, set);
    set.add(what.trim()); return '';
  });
  js = js.replace(/^export default async function /m, 'async function ').replace(/^export default function /m, 'function ');
  js = js.replace(/^export\s+(const|let|var|async function|function|class)\s/gm, '$1 ');
  js = js.replace(/^export \{[^}]*\};?\s*$/gm, '');
  // detect top-level duplicates
  for (const m of js.matchAll(/^(?:const|let|var|async function|function|class)\s+([A-Za-z_$][\w$]*)/gm)) {
    if (seen.has(m[1])) throw new Error(`Duplicate top-level name "${m[1]}" in ${f} and ${seen.get(m[1])}`);
    seen.set(m[1], f);
  }
  body += `\n// ---- server/${f}\n${js}`;
}
let head = '// Generated by scripts/build-api.mjs from server/*.ts. Do not edit by hand.\n';
for (const [mod, set] of externals) {
  const defaults = [], named = [];
  for (const w of set) { const m = w.match(/^([\w$]+)?\s*,?\s*(\{[^}]*\})?$/); if (m?.[1]) defaults.push(m[1]); if (m?.[2]) named.push(m[2].slice(1, -1).trim()); }
  const d = [...new Set(defaults)];
  head += `import ${[d[0], named.length ? `{ ${named.join(', ')} }` : ''].filter(Boolean).join(', ')} from '${mod}';\n`;
}
fs.mkdirSync('api', { recursive: true });
fs.writeFileSync('api/index.js', head + body + '\nexport { config, handler as default };\n');
console.log('api/index.js written,', (head + body).length, 'bytes');
