/** Builds a niche from anything the user types that is not in the list. */
export function customNiche(name: string): NicheCategory {
  const clean = name.trim().slice(0, 80);
  return {
    id: `custom-${clean.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || Date.now()}`,
    name: clean, group: 'Your own niche', iconName: 'Target',
    description: `Short-form content, trends and audience growth in ${clean}.`,
    audienceDemographics: `Creators, buyers and fans interested in ${clean}`,
    avgEngagementRate: '', ...emptyResearch(),
  };
}

